//! Secure update orchestration for the Unison daemon.
//!
//! Trust model:
//! 1. The embedded Ed25519 key authenticates the manifest and payload.
//! 2. HTTPS is required for every remote URL.
//! 3. The manifest pins the exact payload SHA-256 and byte size.
//! 4. Only a staged file under the configured install directory is executable.
//! 5. The old binary is retained until the new process passes healthcheck.

use std::{
    future::Future,
    path::{Path, PathBuf},
    pin::Pin,
    process::Stdio,
    sync::Arc,
    time::Duration,
};

use anyhow::{bail, Context, Result};
use base64::{engine::general_purpose::STANDARD as BASE64, Engine};
use ed25519_dalek::{Signature, Verifier, VerifyingKey};
use reqwest::Client;
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use tokio::{
    fs,
    io::{AsyncReadExt, AsyncWriteExt},
    process::{Child, Command},
    time::timeout,
};
use url::Url;

pub const MAX_MANIFEST_BYTES: usize = 64 * 1024;
pub const MAX_PAYLOAD_BYTES: u64 = 256 * 1024 * 1024;
pub const HEALTHCHECK_TIMEOUT: Duration = Duration::from_secs(5);

/// This key is a placeholder for the release key generated by the project.
/// Replace it before publishing production releases; never load it from the
/// update server or an environment variable.
pub const EMBEDDED_ED25519_PUBLIC_KEY: [u8; 32] = [0u8; 32];

#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct ReleaseManifest {
    pub version: String,
    pub target: String,
    pub payload_url: String,
    pub payload_sha256: String,
    pub payload_size: u64,
    pub payload_signature: String,
    #[serde(default)]
    pub patch_base_version: Option<String>,
}

#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct SignedManifest {
    pub manifest: ReleaseManifest,
    /// Base64 Ed25519 signature over canonical `manifest` JSON.
    pub manifest_signature: String,
}

#[derive(Clone, Debug)]
pub struct UpdateConfig {
    pub manifest_url: Url,
    pub install_dir: PathBuf,
    pub executable_name: String,
    pub target: String,
    pub current_version: String,
    pub check_interval: Duration,
    pub max_payload_bytes: u64,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum InstallResult {
    UpToDate,
    Installed { version: String },
    RestartScheduled { version: String },
}

pub type HealthFuture = Pin<Box<dyn Future<Output = Result<()>> + Send>>;
pub type Healthcheck = Arc<dyn Fn() -> HealthFuture + Send + Sync>;

pub struct Updater {
    client: Client,
    config: UpdateConfig,
    public_key: VerifyingKey,
}

impl Updater {
    pub fn new(config: UpdateConfig) -> Result<Self> {
        validate_config(&config)?;
        let public_key = VerifyingKey::from_bytes(&EMBEDDED_ED25519_PUBLIC_KEY)
            .context("invalid embedded Ed25519 public key")?;
        Ok(Self {
            client: Client::builder()
                .user_agent("unison-updater/1")
                .redirect(reqwest::redirect::Policy::none())
                .build()
                .context("building updater HTTP client")?,
            config,
            public_key,
        })
    }

    pub async fn check_once(&self) -> Result<InstallResult> {
        let manifest = self.fetch_manifest().await?;
        verify_manifest(&manifest, &self.public_key)?;
        if manifest.manifest.target != self.config.target {
            bail!("release target does not match this installation");
        }
        if semver::Version::parse(&manifest.manifest.version)?
            <= semver::Version::parse(&self.config.current_version)?
        {
            return Ok(InstallResult::UpToDate);
        }
        bail!("update is available; call install to apply it")
    }

    pub async fn install(&self, healthcheck: Healthcheck) -> Result<InstallResult> {
        let manifest = self.fetch_manifest().await?;
        verify_manifest(&manifest, &self.public_key)?;
        let release = &manifest.manifest;
        if release.target != self.config.target {
            bail!("release target does not match this installation");
        }
        if semver::Version::parse(&release.version)?
            <= semver::Version::parse(&self.config.current_version)?
        {
            return Ok(InstallResult::UpToDate);
        }

        let payload = self.download_payload(release).await?;
        verify_payload(release, &payload, &self.public_key)?;
        let paths = InstallPaths::new(&self.config.install_dir, &self.config.executable_name);
        paths.prepare().await?;
        fs::write(&paths.staged, &payload)
            .await
            .context("writing staged update")?;
        sync_file(&paths.staged).await?;

        match atomic_swap(&paths).await? {
            SwapResult::Swapped => {
                let mut child = spawn_daemon(&paths.current)?;
                let health_result = timeout(HEALTHCHECK_TIMEOUT, (healthcheck)()).await;
                let healthy = matches!(health_result, Ok(Ok(())));
                if !healthy {
                    let _ = child.kill().await;
                    rollback(&paths).await?;
                    bail!("updated daemon failed the 5-second healthcheck; rolled back");
                }
                cleanup_backup(&paths).await?;
                let _ = child.start_kill();
                Ok(InstallResult::Installed {
                    version: release.version.clone(),
                })
            }
            SwapResult::RestartScheduled => Ok(InstallResult::RestartScheduled {
                version: release.version.clone(),
            }),
        }
    }

    pub async fn run_periodic(self: Arc<Self>, healthcheck: Healthcheck) -> Result<()> {
        loop {
            if let Err(error) = self.install(Arc::clone(&healthcheck)).await {
                eprintln!("Unison update check failed: {error:#}");
            }
            tokio::time::sleep(self.config.check_interval).await;
        }
    }

    async fn fetch_manifest(&self) -> Result<SignedManifest> {
        let response = self
            .client
            .get(self.config.manifest_url.clone())
            .send()
            .await
            .context("fetching release manifest")?;
        require_success_https(&response)?;
        let bytes = response.bytes().await?;
        if bytes.len() > MAX_MANIFEST_BYTES {
            bail!("release manifest exceeds size limit");
        }
        serde_json::from_slice(&bytes).context("parsing signed release manifest")
    }

    async fn download_payload(&self, manifest: &ReleaseManifest) -> Result<Vec<u8>> {
        let url = https_url(&manifest.payload_url)?;
        if manifest.payload_size > self.config.max_payload_bytes {
            bail!("release payload exceeds configured size limit");
        }
        let response = self.client.get(url).send().await?;
        require_success_https(&response)?;
        let declared = response.content_length().unwrap_or(manifest.payload_size);
        if declared != manifest.payload_size {
            bail!("payload content length does not match manifest");
        }
        let mut stream = response.bytes_stream();
        let mut payload = Vec::with_capacity(manifest.payload_size as usize);
        while let Some(chunk) = futures_util::StreamExt::next(&mut stream).await {
            let chunk = chunk?;
            if payload.len() as u64 + chunk.len() as u64 > self.config.max_payload_bytes {
                bail!("payload exceeds configured size limit");
            }
            payload.extend_from_slice(&chunk);
        }
        if payload.len() as u64 != manifest.payload_size {
            bail!("downloaded payload size does not match manifest");
        }
        Ok(payload)
    }
}

fn validate_config(config: &UpdateConfig) -> Result<()> {
    https_url(config.manifest_url.as_str())?;
    if config.install_dir.as_os_str().is_empty()
        || config.executable_name.is_empty()
        || config.target.is_empty()
        || config.max_payload_bytes == 0
    {
        bail!("updater configuration contains an empty or invalid field");
    }
    Ok(())
}

fn https_url(value: &str) -> Result<Url> {
    let url = Url::parse(value).context("invalid updater URL")?;
    if url.scheme() != "https" || url.host_str().is_none() {
        bail!("updater URLs must use HTTPS and include a host");
    }
    Ok(url)
}

fn require_success_https(response: &reqwest::Response) -> Result<()> {
    if response.url().scheme() != "https" {
        bail!("redirected updater response is not HTTPS");
    }
    if !response.status().is_success() {
        bail!("updater server returned {}", response.status());
    }
    Ok(())
}

pub fn verify_manifest(manifest: &SignedManifest, key: &VerifyingKey) -> Result<()> {
    let signed = serde_json::to_vec(&manifest.manifest)?;
    verify_signature(&signed, &manifest.manifest_signature, key)
}

pub fn verify_payload(
    manifest: &ReleaseManifest,
    payload: &[u8],
    key: &VerifyingKey,
) -> Result<()> {
    if payload.len() as u64 != manifest.payload_size {
        bail!("payload length does not match manifest");
    }
    let digest = hex::encode(Sha256::digest(payload));
    if digest != manifest.payload_sha256.to_ascii_lowercase() {
        bail!("payload SHA-256 does not match manifest");
    }
    verify_signature(payload, &manifest.payload_signature, key)
}

fn verify_signature(bytes: &[u8], encoded: &str, key: &VerifyingKey) -> Result<()> {
    let signature_bytes = BASE64
        .decode(encoded)
        .context("invalid base64 Ed25519 signature")?;
    let signature = Signature::from_slice(&signature_bytes).context("invalid Ed25519 signature")?;
    key.verify(bytes, &signature)
        .context("signature verification failed")
}

struct InstallPaths {
    current: PathBuf,
    staged: PathBuf,
    backup: PathBuf,
}

impl InstallPaths {
    fn new(dir: &Path, executable: &str) -> Self {
        Self {
            current: dir.join(executable),
            staged: dir.join(format!("{executable}.staged")),
            backup: dir.join(format!("{executable}.rollback")),
        }
    }

    async fn prepare(&self) -> Result<()> {
        if let Some(parent) = self.current.parent() {
            fs::create_dir_all(parent).await?;
        }
        let _ = fs::remove_file(&self.staged).await;
        let _ = fs::remove_file(&self.backup).await;
        Ok(())
    }
}

enum SwapResult {
    Swapped,
    RestartScheduled,
}

async fn atomic_swap(paths: &InstallPaths) -> Result<SwapResult> {
    #[cfg(windows)]
    {
        if fs::rename(&paths.current, &paths.backup).await.is_err() {
            schedule_windows_rename(&paths.current, &paths.backup)?;
            schedule_windows_rename(&paths.staged, &paths.current)?;
            return Ok(SwapResult::RestartScheduled);
        }
    }
    #[cfg(not(windows))]
    fs::rename(&paths.current, &paths.backup)
        .await
        .context("moving current daemon to rollback path")?;
    fs::rename(&paths.staged, &paths.current)
        .await
        .context("atomically installing staged daemon")?;
    Ok(SwapResult::Swapped)
}

async fn rollback(paths: &InstallPaths) -> Result<()> {
    let _ = fs::remove_file(&paths.current).await;
    fs::rename(&paths.backup, &paths.current)
        .await
        .context("restoring rollback daemon")?;
    Ok(())
}

async fn cleanup_backup(paths: &InstallPaths) -> Result<()> {
    let _ = fs::remove_file(&paths.backup).await;
    Ok(())
}

async fn sync_file(path: &Path) -> Result<()> {
    let mut file = fs::OpenOptions::new().write(true).open(path).await?;
    file.flush().await?;
    file.sync_all().await?;
    Ok(())
}

fn spawn_daemon(path: &Path) -> Result<Child> {
    Command::new(path)
        .arg("--post-update")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .context("spawning updated daemon")
}

#[cfg(windows)]
fn schedule_windows_rename(from: &Path, to: &Path) -> Result<()> {
    use std::{ffi::OsStr, os::windows::ffi::OsStrExt};
    use windows_sys::Win32::Storage::FileSystem::{
        MoveFileExW, MOVEFILE_DELAY_UNTIL_REBOOT, MOVEFILE_REPLACE_EXISTING,
    };
    let from: Vec<u16> = OsStr::new(from)
        .encode_wide()
        .chain(std::iter::once(0))
        .collect();
    let to: Vec<u16> = OsStr::new(to)
        .encode_wide()
        .chain(std::iter::once(0))
        .collect();
    if unsafe {
        MoveFileExW(
            from.as_ptr(),
            to.as_ptr(),
            MOVEFILE_DELAY_UNTIL_REBOOT | MOVEFILE_REPLACE_EXISTING,
        )
    } == 0
    {
        bail!("Windows could not schedule locked-file replacement");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use ed25519_dalek::{Signer, SigningKey};

    #[test]
    fn verifies_signed_manifest_and_payload() {
        let signing_key = SigningKey::from_bytes(&[7u8; 32]);
        let verifying_key = signing_key.verifying_key();
        let payload = b"unison-daemon";
        let release = ReleaseManifest {
            version: "1.2.3".to_owned(),
            target: "x86_64-pc-windows-msvc".to_owned(),
            payload_url: "https://example.test/unison.exe".to_owned(),
            payload_sha256: hex::encode(Sha256::digest(payload)),
            payload_size: payload.len() as u64,
            payload_signature: BASE64.encode(signing_key.sign(payload).to_bytes()),
            patch_base_version: None,
        };
        let manifest = SignedManifest {
            manifest: release.clone(),
            manifest_signature: BASE64.encode(
                signing_key
                    .sign(&serde_json::to_vec(&release).unwrap())
                    .to_bytes(),
            ),
        };
        verify_manifest(&manifest, &verifying_key).unwrap();
        verify_payload(&release, payload, &verifying_key).unwrap();
    }

    #[test]
    fn rejects_non_https_urls() {
        assert!(https_url("http://example.test/release.json").is_err());
    }
}
